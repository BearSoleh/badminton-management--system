import { expect,test } from '@playwright/test'
import { billingFixture } from '../helpers/billing-fixture'

test('real admin attendance, full fee preview/publication and private member charge',async({page},info)=>{
  const f=await billingFixture()
  try {
    const {sid,pids}=await f.session()
    await page.goto('/login')
    await page.getByLabel('Phone number').fill(f.actors[0].phone)
    await page.getByLabel('Password',{exact:true}).fill(f.actors[0].password)
    await page.getByRole('button',{name:'Log in',exact:true}).click()
    await expect(page.getByRole('heading',{name:'Welcome back, Synthetic Billing Admin.'})).toBeVisible()
    await page.goto(`/admin/sessions/${sid}`)
    await page.getByRole('link',{name:'Manage attendance & fees',exact:true}).click()
    await expect(page.getByText('Fee not yet set',{exact:true})).toBeVisible()
    await expect(page.getByRole('button',{name:'Review charges',exact:true})).toBeDisabled()
    await page.getByLabel('Attendance for Synthetic Billing Player 1').selectOption('present')
    await expect(page.getByText('1 unmarked',{exact:true})).toBeVisible()
    await page.getByLabel('Attendance for Synthetic Billing Player 2').selectOption('no_show')
    await expect(page.getByText('0 unmarked',{exact:true})).toBeVisible()
    await page.getByLabel('Full per-player fee (RM)').fill('20.01')
    await page.getByLabel('Court cost (RM)').fill('100.00')
    await page.getByLabel('Shuttles used').fill('3')
    await page.getByLabel('Shuttle cost (RM)').fill('45.00')
    await page.getByLabel('Cost notes').fill('Synthetic private court and shuttle notes')
    await page.getByRole('button',{name:'Review charges',exact:true}).click()
    const preview=page.getByRole('region',{name:'Charge preview'})
    await expect(preview).toContainText('RM 15.01')
    await expect(preview).toContainText('Confirmed no-show')
    expect((await f.operator.from('sessions').select('billing_status').eq('id',sid).single()).data?.billing_status).toBe('not_published')
    await page.getByLabel('I reviewed every participant’s charge.').check()
    await page.getByRole('button',{name:'Publish fees',exact:true}).focus()
    await expect(page.getByRole('button',{name:'Publish fees',exact:true})).toBeFocused()
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    await page.screenshot({path:`.superpowers/task5-review-${info.project.name}.png`,fullPage:true})
    await page.keyboard.press('Enter')
    await expect(page.getByText('Published fee version 1.',{exact:true})).toBeVisible()
    const charges=await f.operator.from('charges').select('participant_id,amount_sen,percent').eq('session_id',sid)
    expect(charges.data?.find(c=>c.participant_id===pids[2])).toMatchObject({amount_sen:1501,percent:75})
    await page.getByRole('button',{name:'Log out',exact:true}).click()
    await page.getByLabel('Phone number').fill(f.actors[2].phone)
    await page.getByLabel('Password',{exact:true}).fill(f.actors[2].password)
    await page.getByRole('button',{name:'Log in',exact:true}).click()
    await expect(page.getByRole('heading',{name:'Welcome back, Synthetic Billing Player 2.'})).toBeVisible()
    await page.goto(`/app/sessions/${sid}`)
    const own=page.getByRole('region',{name:'Your participation'})
    await expect(own).toContainText('Your charge: RM 20.01')
    await expect(own).toContainText('100%')
    await expect(page.getByText('Fee not yet set',{exact:true})).toHaveCount(0)
    await expect(page.getByText('Synthetic private court and shuttle notes')).toHaveCount(0)
    await expect(page.getByRole('link',{name:'Manage attendance & fees'})).toHaveCount(0)
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    await page.screenshot({path:`.superpowers/task5-member-${info.project.name}.png`,fullPage:true})
    await page.getByRole('button',{name:'Log out',exact:true}).click()
  }finally{await f.cleanup()}
})
