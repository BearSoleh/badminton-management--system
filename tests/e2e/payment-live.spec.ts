import { expect,test } from '@playwright/test'
import { paymentFixture,receiptPdf } from '../helpers/payment-fixture'
import { localSql,sqlLiteral as q } from '../helpers/local-sql'

test('real private receipt reject/resubmit, bank approval, cash, fee adjustment and cancellation/refund history',async({page},info)=>{
  const f=await paymentFixture()
  async function login(actor:number) {
    await page.goto('/login');await page.getByLabel('Phone number').fill(f.actors[actor].phone);await page.getByLabel('Password',{exact:true}).fill(f.actors[actor].password)
    await page.getByRole('button',{name:'Log in',exact:true}).click()
    await expect(page.getByRole('heading',{name:`Welcome back, ${actor===0?'Synthetic Billing Admin':`Synthetic Billing Player ${actor}`}.`})).toBeVisible()
  }
  async function logout(){await page.getByRole('button',{name:'Log out',exact:true}).click();await expect(page.getByRole('heading',{name:'Good to see you.'})).toBeVisible()}
  try {
    const s=await f.ready()
    await login(1);await page.goto(`/app/payments/${s.charge.id}`)
    await page.getByLabel('Receipt file').setInputFiles({name:'synthetic-receipt.pdf',mimeType:'application/pdf',buffer:Buffer.from(receiptPdf)})
    await page.getByRole('button',{name:'Submit for verification',exact:true}).click()
    await expect(page.getByText('Pending verification',{exact:true}).first()).toBeVisible()
    // Capture exact test-owned paths for Storage API cleanup, including browser uploads.
    const paths=async()=>{const p=await f.operator.from('payments').select('receipt_object_path').eq('charge_id',s.charge.id);for(const row of p.data??[])if(row.receipt_object_path&&!f.objects.includes(row.receipt_object_path))f.objects.push(row.receipt_object_path)}
    await paths();await logout();await login(0);await page.goto('/admin/payments')
    const first=page.getByRole('article',{name:'Synthetic Billing Player 1, Synthetic Task 5 game, version 1',exact:true})
    await first.getByRole('button',{name:'Get receipt download',exact:true}).click()
    const downloadLink=first.getByRole('link',{name:'Download receipt (valid for 60 seconds)'})
    await expect(downloadLink).toBeVisible()
    const receipt=await page.request.get((await downloadLink.getAttribute('href'))!)
    expect(receipt.status()).toBe(200);expect(await receipt.body()).toEqual(Buffer.from(receiptPdf))
    await first.getByLabel('Review reason or bank reference').fill('Synthetic bank match not found')
    await first.getByRole('button',{name:'Reject receipt',exact:true}).click()
    await expect(first.getByText('Synthetic bank match not found')).toBeVisible()
    await logout();await login(1);await page.goto(`/app/payments/${s.charge.id}`)
    await expect(page.getByText('Synthetic bank match not found')).toBeVisible()
    await page.getByLabel('Receipt file').setInputFiles({name:'synthetic-replacement.pdf',mimeType:'application/pdf',buffer:Buffer.from(receiptPdf)})
    await page.getByRole('button',{name:'Submit for verification',exact:true}).click()
    await expect(page.getByText('Pending verification',{exact:true}).first()).toBeVisible();await paths()
    await logout();await login(0);await page.goto('/admin/payments')
    const pending=first.getByRole('listitem').filter({has:page.getByRole('button',{name:'Approve payment',exact:true})})
    await pending.getByLabel('I checked this full amount against the bank transaction.').check()
    await pending.getByLabel('Review reason or bank reference').fill('Synthetic full amount confirmed')
    await pending.getByRole('button',{name:'Approve payment',exact:true}).focus();await page.keyboard.press('Enter')
    await expect(first.getByText('Paid',{exact:true})).toBeVisible()
    const second=page.getByRole('article',{name:'Synthetic Billing Player 2, Synthetic Task 5 game, version 1',exact:true})
    await second.getByLabel('Cash receipt reason').fill('Synthetic full cash received')
    await second.getByLabel('I received the full amount in cash.').check()
    await second.getByRole('button',{name:'Record full cash payment',exact:true}).click()
    await expect(second.getByText('Paid',{exact:true})).toBeVisible()
    await page.goto(`/admin/sessions/${s.sid}/attendance`)
    await page.getByLabel('Full per-player fee (RM)').fill('25.00')
    await page.getByLabel('Fee correction reason').fill('Synthetic corrected court cost')
    await page.getByRole('button',{name:'Review charges',exact:true}).click()
    await page.getByLabel('I reviewed every participant’s charge.').check()
    await expect(page.getByRole('button',{name:'Publish fee adjustment',exact:true})).toBeDisabled()
    await page.getByLabel('I will return the full received payments manually and collect the replacement full charges.').check()
    await page.getByRole('button',{name:'Publish fee adjustment',exact:true}).click()
    await expect(page.getByText('Published fee version 2.',{exact:true})).toBeVisible()
    await page.goto('/admin/payments')
    await expect(first.getByText('Manual refund pending',{exact:true})).toBeVisible()
    await first.getByLabel('Refund reason and reference').fill('Synthetic full bank refund returned, test reference')
    await first.getByLabel('I have returned the full payment to the player.').check()
    await first.getByRole('button',{name:'Record actual full refund',exact:true}).click()
    await expect(first.getByText('Full refund recorded',{exact:true})).toBeVisible()
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    await page.screenshot({path:`.superpowers/task6-admin-history-${info.project.name}.png`,fullPage:true})
    await page.goto(`/admin/sessions/${s.sid}`)
    await page.getByRole('button',{name:'Review cancellation',exact:true}).click()
    await page.getByLabel('Cancellation reason').fill('Synthetic court closure')
    await page.getByLabel('Cancel this session and track any received money for manual refund.').check()
    await page.getByRole('button',{name:'Confirm cancellation',exact:true}).click()
    await expect(page.getByText('Cancelled',{exact:true})).toBeVisible()
    const money=await f.operator.from('payments').select('status,refund_status,amount_sen').in('charge_id',s.charges.map(c=>c.id))
    expect(money.data).toEqual(expect.arrayContaining([{status:'approved',refund_status:'refunded',amount_sen:2001},{status:'approved',refund_status:'pending',amount_sen:2001}]))
    expect((await f.operator.from('charges').select('status').eq('session_id',s.sid).eq('is_current',true)).data?.every(c=>c.status==='voided')).toBe(true)
    await logout();localSql(`update public.memberships set status='suspended' where user_id=${q(f.actors[1].uid)}`)
    await page.goto('/login');await page.getByLabel('Phone number').fill(f.actors[1].phone);await page.getByLabel('Password',{exact:true}).fill(f.actors[1].password);await page.getByRole('button',{name:'Log in',exact:true}).click()
    await page.getByRole('link',{name:'Your payments',exact:true}).click()
    await expect(page.getByRole('heading',{name:'Your payments'})).toBeVisible()
    await page.goto(`/app/payments/${s.charge.id}`)
    await expect(page.getByText('Full refund recorded',{exact:true})).toBeVisible()
    await expect(page.getByText('Synthetic bank match not found')).toBeVisible()
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    await page.screenshot({path:`.superpowers/task6-member-history-${info.project.name}.png`,fullPage:true})
    await logout()
  }finally{
    // Include any successfully submitted browser receipt even if a later assertion failed.
    const payments=await f.operator.from('payments').select('receipt_object_path').in('charge_id',(await f.operator.from('charges').select('id').in('session_id',f.sessions)).data?.map(c=>c.id)??[])
    for(const p of payments.data??[])if(p.receipt_object_path&&!f.objects.includes(p.receipt_object_path))f.objects.push(p.receipt_object_path)
    await f.cleanup()
  }
})
