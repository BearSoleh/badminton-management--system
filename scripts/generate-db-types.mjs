import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { createIdentityDatabase } from '../tests/helpers/identity-db.mjs'

// Deterministic introspection of ordered migrations, using a real PostgreSQL engine.
// Auth schema is a test fixture; only our public schema is emitted. Compare with
// `supabase gen types typescript --local` when a complete local stack is available.
const db = await createIdentityDatabase()
const typeMap = { uuid: 'string', text: 'string', timestamptz: 'string', bool: 'boolean', int2: 'number', int4: 'number', int8: 'number', void: 'undefined', jsonb: 'Json' }
const ts = (type) => { if (!typeMap[type]) throw new Error(`Add a deliberate mapping for PostgreSQL type ${type}`); return typeMap[type] }
const tables = (await db.query("select tablename from pg_tables where schemaname='public' order by tablename")).rows
let output = '// Generated by npm run db:types from the public migration schema. Do not edit.\n'
output += 'export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]\n\nexport type Database = { public: {\n  Tables: {\n'
for (const { tablename } of tables) {
  const { rows: columns } = await db.query(`select a.attname as name, t.typname as type, a.attnotnull as required,
    (d.oid is not null) as has_default from pg_attribute a join pg_class c on c.oid=a.attrelid
    join pg_namespace n on n.oid=c.relnamespace join pg_type t on t.oid=a.atttypid
    left join pg_attrdef d on d.adrelid=a.attrelid and d.adnum=a.attnum
    where n.nspname='public' and c.relname=$1 and a.attnum>0 and not a.attisdropped order by a.attnum`, [tablename])
  output += `    ${tablename}: {\n`
  for (const shape of ['Row', 'Insert', 'Update']) {
    output += `      ${shape}: {\n`
    for (const column of columns) {
      const optional = shape === 'Update' || (shape === 'Insert' && (!column.required || column.has_default))
      const valueType = column.type === 'jsonb' && column.required ? 'NonNullable<Json>' : ts(column.type)
      output += `        ${column.name}${optional ? '?' : ''}: ${valueType}${column.required ? '' : ' | null'}\n`
    }
    output += '      }\n'
  }
  const { rows: relations } = await db.query(`select con.conname,
    array(select a.attname from unnest(con.conkey) with ordinality x(attnum,n) join pg_attribute a on a.attrelid=con.conrelid and a.attnum=x.attnum order by x.n) as column_names,
    foreign_class.relname as foreign_table,
    array(select a.attname from unnest(con.confkey) with ordinality x(attnum,n) join pg_attribute a on a.attrelid=con.confrelid and a.attnum=x.attnum order by x.n) as foreign_columns,
    exists(select 1 from pg_constraint uq where uq.conrelid=con.conrelid and uq.contype in ('p','u') and uq.conkey @> con.conkey and uq.conkey <@ con.conkey) as is_one_to_one
    from pg_constraint con join pg_class own on own.oid=con.conrelid join pg_namespace own_ns on own_ns.oid=own.relnamespace
    join pg_class foreign_class on foreign_class.oid=con.confrelid join pg_namespace foreign_ns on foreign_ns.oid=foreign_class.relnamespace
    where con.contype='f' and own_ns.nspname='public' and foreign_ns.nspname='public' and own.relname=$1 order by con.conname`, [tablename])
  output += '      Relationships: [\n'
  const tuple = (items) => `[${items.map((item) => `'${item}'`).join(', ')}]`
  for (const r of relations) output += `        { foreignKeyName: '${r.conname}'; columns: ${tuple(r.column_names)}; isOneToOne: ${r.is_one_to_one}; referencedRelation: '${r.foreign_table}'; referencedColumns: ${tuple(r.foreign_columns)} },\n`
  output += '      ]\n    }\n'
}
output += '  }\n  Views: { [_ in never]: never }\n  Functions: {\n'
const { rows: functions } = await db.query(`select p.proname, p.proargnames as names, p.proargmodes as modes,
  array(select typname from unnest(coalesce(p.proallargtypes,p.proargtypes::oid[])) with ordinality as x(id,n) join pg_type t on t.oid=x.id order by x.n) as types,
  t.typname as return_type from pg_proc p join pg_namespace n on n.oid=p.pronamespace join pg_type t on t.oid=p.prorettype
  where n.nspname='public' order by p.proname`)
for (const f of functions) {
  const inputs = [], outputs = []
  for (let i = 0; i < (f.names?.length ?? 0); i++) {
    const item = `${f.names[i]}: ${ts(f.types[i])}`
    if (!f.modes || f.modes[i] === 'i') inputs.push(item)
    else if (f.modes[i] === 't') outputs.push(item)
    else throw new Error('Unsupported function argument mode')
  }
  output += `    ${f.proname}: { Args: ${inputs.length ? `{ ${inputs.join('; ')} }` : 'Record<PropertyKey, never>'}; Returns: ${outputs.length ? `{ ${outputs.join('; ')} }[]` : ts(f.return_type)} }\n`
}
output += '  }\n  Enums: { [_ in never]: never }\n  CompositeTypes: { [_ in never]: never }\n} }\n'
await db.close()
await mkdir('src/types', { recursive: true })
if (process.argv.includes('--check')) {
  if (await readFile('src/types/database.ts', 'utf8') !== output) { console.error('Database types are stale. Run npm run db:types.'); process.exit(1) }
  console.log('Database types match the migrations.')
} else { await writeFile('src/types/database.ts', output); console.log('Generated src/types/database.ts from ordered migrations (PGlite PostgreSQL).') }
